const grid=document.getElementById("scriptGrid"),search=document.getElementById("search"),empty=document.getElementById("empty"),toast=document.getElementById("toast");
let activeFilter="all";
function esc(s){return String(s).replace(/[&<>"']/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[m]))}
function render(){
  const q=search.value.trim().toLowerCase();
  const list=SCRIPTS.filter(x=>{
    const match=(x.name+" "+x.description+" "+x.features.join(" ")).toLowerCase().includes(q);
    const filter=activeFilter==="all" || x.status===activeFilter || (activeFilter==="new" && ["Driving Empire","Steal a Egg","Lift a Cube"].includes(x.name));
    return match&&filter;
  });
  grid.innerHTML=list.map((x,i)=>`
  <article class="script-card">
    <div class="game-image">
      ${x.image?`<img src="assets/${esc(x.image)}" alt="${esc(x.name)} screenshot" loading="lazy">`:`<div class="placeholder">${esc(x.name)}</div>`}
      <span class="status">● ${esc(x.status)}</span>
    </div>
    <div class="card-body">
      <div class="title-row"><h3>${esc(x.name)}</h3></div>
      <p>${esc(x.description)}</p>
      <div class="features">${x.features.map(f=>`<span class="feature">✓ ${esc(f)}</span>`).join("")}</div>
      <div class="load-label">LOADSTRING</div>
      <div class="code-row"><div class="code" title="${esc(x.loadstring)}">${esc(x.loadstring)}</div><button class="copy" data-copy="${encodeURIComponent(x.loadstring)}" aria-label="Copy loadstring">📋</button></div>
      <button class="copy-main" data-copy="${encodeURIComponent(x.loadstring)}">COPY LOADSTRING</button>
    </div>
  </article>`).join("");
  empty.hidden=list.length!==0;
}
document.addEventListener("click",e=>{
  const b=e.target.closest("[data-copy]");
  if(b){const value=decodeURIComponent(b.dataset.copy);navigator.clipboard?.writeText(value).then(()=>showToast()).catch(()=>fallbackCopy(value))}
});
function fallbackCopy(v){const t=document.createElement("textarea");t.value=v;document.body.appendChild(t);t.select();document.execCommand("copy");t.remove();showToast()}
function showToast(){toast.classList.add("show");clearTimeout(window.toastTimer);window.toastTimer=setTimeout(()=>toast.classList.remove("show"),1800)}
search.addEventListener("input",render);
document.querySelectorAll(".filter").forEach(b=>b.addEventListener("click",()=>{document.querySelectorAll(".filter").forEach(x=>x.classList.remove("active"));b.classList.add("active");activeFilter=b.dataset.filter;render()}));
document.getElementById("menuBtn").addEventListener("click",()=>document.getElementById("navLinks").classList.toggle("open"));
